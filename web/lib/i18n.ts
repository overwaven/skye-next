export function translateServerMessage(locale: Locale, message: string) {
  if (locale !== "ru") return message
  const value = message.trim()
  return (
    serverMessagesRu[value] ??
    serverMessagesRu[`${value}.`] ??
    serverMessagesRu[value.replace(/\.$/, "")] ??
    value
  )
}

export const messages: Record<Locale, Record<MessageKey, string>> = { en, ru }

export type MessageValues = Record<string, string | number>

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "ru"
}

export function negotiateLocale(
  acceptLanguage: string | null | undefined
): Locale {
  if (!acceptLanguage) return defaultLocale
  const preferred = acceptLanguage
    .split(",")
    .map((part) => {
      const [tag, ...parameters] = part.trim().toLowerCase().split(";")
      const quality = parameters
        .map((parameter) => parameter.trim())
        .find((parameter) => parameter.startsWith("q="))
      return {
        tag,
        quality: quality ? Number(quality.slice(2)) : 1,
      }
    })
    .sort((left, right) => right.quality - left.quality)
  for (const { tag } of preferred) {
    if (tag === "ru" || tag.startsWith("ru-")) return "ru"
    if (tag === "en" || tag.startsWith("en-")) return "en"
  }
  return defaultLocale
}

function interpolate(template: string, values?: MessageValues) {
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match
  )
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values?: MessageValues
) {
  return interpolate(messages[locale][key] ?? messages.en[key], values)
}

export type PluralForm = "one" | "few" | "many" | "other"

export function pluralForm(locale: Locale, count: number): PluralForm {
  if (locale === "ru") {
    const mod10 = count % 10
    const mod100 = count % 100
    if (mod10 === 1 && mod100 !== 11) return "one"
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few"
    return "many"
  }
  return count === 1 ? "one" : "other"
}

export type CountMessageBase =
  | "chats.selected"
  | "chats.deleteTitle"
  | "chat.tools"

export function translateCount(
  locale: Locale,
  base: CountMessageBase,
  count: number,
  values?: MessageValues
) {
  const form = pluralForm(locale, count)
  const dictionary = messages[locale]
  const key = `${base}.${form}` as MessageKey
  return interpolate(dictionary[key] ?? dictionary[`${base}.other`], {
    count,
    ...values,
  })
}
